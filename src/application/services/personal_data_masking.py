"""Маскировка личных данных в текстах запросов перед анализом.

JSON-выгрузка остаётся полной — это исходные данные. Всё, что попадает в отчёт
(цитаты, подписи тем), строится уже из замаскированного текста: телефоны, почта,
пароли и токены заменяются метками до классификации и группировки.
"""
import re

_EMAIL = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
# значение после «пароль»/«логин»/«токен»: через двоеточие или «=»,
# либо слово, похожее на секрет (есть цифры или спецсимволы) — «пароль не подходит» не трогаем
_SECRET = re.compile(
    r"(?i)\b(пароль|парол[ья]|password|pass|passwd|логин|логін|login|токен|token)"
    r"(\s*[:=]\s*\S+|\s+(?=\S*[\d!@#$%^&*_])\S+)"
)
# длинные строки из букв и цифр — токены, ключи API
_TOKEN = re.compile(r"\b(?=[A-Za-z0-9_-]*\d)(?=[A-Za-z0-9_-]*[A-Za-z])[A-Za-z0-9_-]{24,}\b")
# 10 и больше цифр подряд, можно с пробелами, скобками и дефисами: телефоны, карты, счета
_LONG_NUMBER = re.compile(r"\+?\d(?:[\s()-]*\d){9,}")


def mask_personal_data(text: str) -> str:
    text = _EMAIL.sub("[почта]", text)
    text = _SECRET.sub(lambda m: f"{m[1]} [скрыто]", text)
    text = _TOKEN.sub("[токен]", text)
    return _LONG_NUMBER.sub("[номер]", text)
