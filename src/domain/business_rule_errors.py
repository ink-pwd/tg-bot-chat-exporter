"""Нарушения бизнес-правил: беседа не найдена, день недоступен для выгрузки, неверный часовой пояс."""
class DomainError(Exception):
    """Базовая ошибка бизнес-правил."""


class ChatNotFound(DomainError):
    """Беседы нет или она принадлежит другому пользователю.

    Эти случаи намеренно не различаются: чужой пользователь не должен
    узнать, что беседа с таким id существует.
    """


class InvalidExportDay(DomainError):
    """Нельзя выгрузить день, который ещё не наступил."""


class ExportDayTooOld(DomainError):
    """День старше окна выгрузки: его сообщения уже удалены по сроку хранения."""


class InvalidTimezone(DomainError):
    pass
