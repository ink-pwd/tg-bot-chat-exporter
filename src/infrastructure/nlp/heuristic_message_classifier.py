"""Эвристики о смысле сообщения (ru/uk): приветствие, «секунду, уточню», вопрос.

Не идеальный классификатор, а предсказуемые правила — их легко проверить и дополнить.
"""
import re

_WORD = re.compile(r"[a-zа-яёіїєґ'+]+")

# сообщение целиком из таких слов — не обращение и не ответ
_TRIVIAL_WORDS = {
    # приветствия
    "привет", "здравствуйте", "здрасте", "здравствуй", "добрый", "доброе", "доброго", "день",
    "вечер", "утро", "утра", "дня", "вечера", "суток", "времени", "приветствую", "хай", "hi", "hello",
    "вітаю", "привіт", "добрий", "добрий", "вечір", "ранку", "вечора", "доброї", "доби",
    # благодарности и подтверждения
    "спасибо", "спасибочки", "благодарю", "большое", "огромное", "дякую", "дуже", "щиро",
    "ок", "окей", "ok", "okay", "хорошо", "отлично", "понял", "поняла", "понятно", "ясно",
    "добре", "чудово", "зрозумів", "зрозуміла", "зрозуміло", "ага", "угу", "да", "так", "нет", "ні",
    "супер", "класс", "клас", "+", "++", "пожалуйста", "будь", "ласка", "взаимно", "навзаєм",
    "всего", "доброго", "до", "свидания", "побачення", "хорошего", "гарного", "і", "и", "вам", "тебе",
}

# поддержка взяла паузу, но ещё не ответила
_HOLDING_MARKERS = {
    "секунду", "секундочку", "секунда", "минуту", "минутку", "момент", "мгновение",
    "уточню", "уточняю", "проверю", "проверяю", "посмотрю", "смотрю", "гляну", "подождите",
    "ожидайте", "хвилинку", "хвилину", "секундочку", "перевірю", "перевіряю", "подивлюсь",
    "подивлюся", "дивлюсь", "зачекайте", "очікуйте", "уточнюю",
}
_HOLDING_MAX_WORDS = 8

_QUESTION_WORDS = {
    # ru
    "как", "где", "почему", "зачем", "когда", "сколько", "какой", "какая", "какие", "каким",
    "куда", "откуда", "что", "чем", "можно", "ли",
    # uk
    "як", "де", "чому", "навіщо", "коли", "скільки", "який", "яка", "які", "яким", "куди",
    "звідки", "що", "чим", "можна", "чи",
}
_REQUEST_PATTERNS = re.compile(
    r"не\s+(?:приход|пришл|получа|работа|могу|можу|грузит|открыва|проход|прийшл|приходить|"
    r"отримую|працю|завантаж|відкрива|вдається|удается)|"
    r"подскаж|помогите|помочь|підкаж|допоможіть|допомож|"
    r"ошибк|помилк|проблем|сломал|зламал|"
    r"хочу|хотел|хотіл|нужно|надо|треба|потрібн|необходимо",
)


class HeuristicMessageClassifier:
    def is_trivial(self, text: str) -> bool:
        words = _WORD.findall(text.lower())
        return all(word in _TRIVIAL_WORDS for word in words)

    def is_holding_reply(self, text: str) -> bool:
        words = [w for w in _WORD.findall(text.lower()) if w not in _TRIVIAL_WORDS]
        return 0 < len(words) <= _HOLDING_MAX_WORDS and any(w in _HOLDING_MARKERS for w in words)

    def is_question(self, text: str) -> bool:
        if self.is_trivial(text):
            return False
        lowered = text.lower()
        if "?" in lowered:
            return True
        words = _WORD.findall(lowered)
        if any(word in _QUESTION_WORDS for word in words):
            return True
        return bool(_REQUEST_PATTERNS.search(lowered))
